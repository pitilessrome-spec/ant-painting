// Builds js/raid-practice-engine.js: the real server raid engine (raid-engine, boss-mechanics,
// ant-evolution) wrapped for the browser so Practice mode plays exactly the server's rules offline.
// Run after changing any of those files:  node tools/build-raid-practice.mjs
// tests/practice-bundle.test.js fails if the committed bundle is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lib = join(root, 'telegram-backend', 'lib');
const MODULES = ['ant-evolution', 'boss-mechanics', 'raid-engine'];

export function build() {
  const parts = MODULES.map(name => {
    const src = readFileSync(join(lib, name + '.js'), 'utf8');
    return `  defs[${JSON.stringify('./' + name)}] = function (module, exports, require, process) {\n${src}\n  };`;
  });
  return `/* GENERATED by tools/build-raid-practice.mjs from telegram-backend/lib — do not edit by hand. */
(function () {
  'use strict';
  // Browser stand-ins for the two Node APIs the engine uses. Practice mode never talks to a server,
  // so a non-cryptographic hash is enough for team aliases.
  const nodeCrypto = {
    randomBytes(n) { const b = new Uint8Array(n); crypto.getRandomValues(b); return { readUInt32LE: () => (b[0] | b[1] << 8 | b[2] << 16 | b[3] << 24) >>> 0 }; },
    createHash() { let text = ''; return { update(s) { text += String(s); return this; }, digest() { let h = 2166136261 >>> 0, out = ''; for (let k = 0; k < 8; k++) { for (let i = 0; i < text.length; i++) { h ^= text.charCodeAt(i) + k; h = Math.imul(h, 16777619) >>> 0; } out += h.toString(16).padStart(8, '0'); } return out; } };
    },
  };
  const process = { env: { ANT_RAID_V7: '1', ANT_RAID_V6: '1' } };
  const defs = {}, cache = {};
  function require(name) {
    if (name === 'node:crypto') return nodeCrypto;
    const key = name.replace(/\\.js$/, '');
    if (cache[key]) return cache[key].exports;
    const module = cache[key] = { exports: {} };
    defs[key](module, module.exports, require, process);
    return module.exports;
  }
${parts.join('\n')}
  window.AntRaidPractice = { engine: require('./raid-engine'), mechanics: require('./boss-mechanics'), ants: require('./ant-evolution') };
})();
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(root, 'js', 'raid-practice-engine.js'), build());
  console.log('wrote js/raid-practice-engine.js');
}
